#!/usr/bin/env python3
"""Build an investor-ready VC Lab / Founder Institute Data Room from .startup/ state.

Generates:
  data-room/
    index.html                              (interactive local investor portal)
    DATA_ROOM_INDEX.md                      (diligence table of contents + readiness score)
    01_Executive_Summary/ONE_PAGER.md
    02_Pitch_Deck/                          (copies pitch-deck/index.html & DECK.md if present)
    03_Metrics_and_PMF/                     (copies dashboard/index.html, PMF & investor update)
    04_Pipeline_and_Proof/CUSTOMER_PROOF.md (PII-redacted PACTs & discovery proof)
    05_Governance_and_Diligence/DILIGENCE_CHECKLIST.md
"""

from __future__ import annotations

import argparse
import html
import json
import shutil
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


def _load_json(path: Path, default: Any) -> Any:
    if not path.exists():
        return default
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return default


def _fmt_money(val: Any) -> str:
    try:
        num = float(val)
    except (TypeError, ValueError):
        return "$0"
    if abs(num) >= 1_000_000:
        return f"${num / 1_000_000:,.2f}M"
    if abs(num) >= 1_000:
        return f"${num:,.0f}"
    return f"${num:,.2f}"


def _copy_if_exists(src: Path, dest_dir: Path) -> str | None:
    if src.exists() and src.is_file():
        dest_dir.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dest_dir / src.name)
        return src.name
    return None


def build_data_room(workspace: Path) -> dict[str, Any]:
    ws = workspace.resolve()
    startup_dir = ws / ".startup"
    state = _load_json(startup_dir / "state.json", {})
    assumptions = _load_json(startup_dir / "assumptions.json", [])
    interviews = _load_json(startup_dir / "interviews.json", [])
    pacts = _load_json(startup_dir / "pacts.json", [])
    pmf = _load_json(startup_dir / "pmf.json", {})
    sprints = _load_json(startup_dir / "sprints.json", [])

    company = state.get("companyName") or ws.name
    stage = state.get("stage", "idea")
    pitch = state.get("oneSentencePitch") or "[HYPOTHESIS] FI One-Sentence Pitch not yet finalized."
    secret_sauce = state.get("secretSauce") or "[HYPOTHESIS] Secret sauce pending validation."
    metrics = state.get("metrics", {})
    mrr = metrics.get("mrrUsd", 0)
    gm = metrics.get("grossMarginPct", 0)
    cash = metrics.get("cashOnHandUsd", 0)
    burn = metrics.get("monthlyBurnUsd", 0)
    runway = round(cash / burn, 1) if burn and burn > 0 else None
    ikpi = state.get("ikpi", {})

    dr = ws / "data-room"
    d01 = dr / "01_Executive_Summary"
    d02 = dr / "02_Pitch_Deck"
    d03 = dr / "03_Metrics_and_PMF"
    d04 = dr / "04_Pipeline_and_Proof"
    d05 = dr / "05_Governance_and_Diligence"
    for d in (d01, d02, d03, d04, d05):
        d.mkdir(parents=True, exist_ok=True)

    now_iso = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    # 1. Executive Summary One-Pager
    customer_pacts = [p for p in pacts if p.get("type", "customer") == "customer"]
    investor_pacts = [p for p in pacts if p.get("type") == "investor"]
    signed_customer_val = sum(
        float(p.get("amountUsd", 0) or 0)
        for p in customer_pacts
        if p.get("status") in ("signed", "paid", "closed")
    )
    soft_circle_val = sum(
        float(p.get("amountUsd", 0) or 0)
        for p in investor_pacts
        if p.get("status") in ("soft_circled", "signed", "wired", "closed")
    )
    pmf_responses = pmf.get("responses", [])
    very_disappointed = sum(1 for r in pmf_responses if r.get("disappointment") == "very_disappointed")
    sean_ellis_pct = round((very_disappointed / len(pmf_responses)) * 100, 1) if pmf_responses else None

    one_pager = f"""# {company} — Investor Executive Summary

> Generated by Startup Antigravity Data Room Builder • {now_iso}
> Tagging discipline: `[VALIDATED]` = logged primary evidence; `[HYPOTHESIS]` = unverified assumption.

## 1. One-Sentence Pitch (FI Standard)
> {pitch}

- **Stage:** `{stage}`
- **Secret Sauce / Unfair Advantage:** {secret_sauce}

## 2. Traction & Financial Snapshot
| Metric | Current Value | Evidence Status |
| :--- | :--- | :--- |
| Monthly Recurring Revenue (MRR) | {_fmt_money(mrr)} | {"[VALIDATED]" if mrr and mrr > 0 else "[HYPOTHESIS]"} |
| Gross Margin | {gm}% | {"[VALIDATED]" if gm and gm > 0 else "[HYPOTHESIS]"} |
| Cash on Hand | {_fmt_money(cash)} | {"[VALIDATED]" if cash and cash > 0 else "[HYPOTHESIS]"} |
| Monthly Net Burn | {_fmt_money(burn)} | {"[VALIDATED]" if burn and burn > 0 else "[HYPOTHESIS]"} |
| Estimated Runway | {f"{runway} months" if runway is not None else "Default-Alive / N/A"} | Computed |
| Signed / Paid Customer PACTs | {_fmt_money(signed_customer_val)} ({len(customer_pacts)} total) | {"[VALIDATED]" if signed_customer_val > 0 else "[HYPOTHESIS]"} |
| Investor Soft-Circle PACTs | {_fmt_money(soft_circle_val)} ({len(investor_pacts)} total) | {"[VALIDATED]" if soft_circle_val > 0 else "[HYPOTHESIS]"} |
| Sean Ellis PMF Score | {f"{sean_ellis_pct}% Very Disappointed (n={len(pmf_responses)})" if sean_ellis_pct is not None else "Not yet measured"} | {"[VALIDATED]" if sean_ellis_pct is not None else "[HYPOTHESIS]"} |

## 3. For-Progress Impact Thesis (iKPI)
- **UN SDG Alignment:** {ikpi.get("sdg", "Not specified")}
- **Primary iKPI:** {ikpi.get("metric", "Not specified")}
- **Current / Target:** {ikpi.get("current", 0)} / {ikpi.get("target", "TBD")}

## 4. Mensarius Oath & Ethical Governance
{company} commits to transparent reporting, zero dark patterns, fair stakeholder equity (FI FAST standard for advisors), and verified bottom-up metrics.
"""
    (d01 / "ONE_PAGER.md").write_text(one_pager, encoding="utf-8")

    # 2. Pitch Deck artifacts
    copied_deck: list[str] = []
    for src in (ws / "pitch-deck" / "index.html", ws / "pitch-deck" / "DECK.md"):
        name = _copy_if_exists(src, d02)
        if name:
            copied_deck.append(name)

    # 3. Metrics, Dashboard & PMF
    copied_metrics: list[str] = []
    for src in (
        ws / "dashboard" / "index.html",
        ws / "docs" / "PMF_SCORECARD.md",
        ws / "docs" / "INVESTOR_UPDATE.md",
        ws / "docs" / "METRICS_DASHBOARD.md",
    ):
        name = _copy_if_exists(src, d03)
        if name:
            copied_metrics.append(name)

    # 4. Customer Proof & Pipeline (PII-Redacted)
    validated_assumptions = [a for a in assumptions if a.get("status") == "validated"]
    proof_lines = [
        f"# {company} — Anonymized Customer Proof & Discovery Log",
        "",
        "> **Privacy Hygiene:** Raw customer emails, phone numbers, and personal PII are intentionally omitted from this investor data room.",
        "",
        f"## Discovery Summary",
        f"- **Logged Mom Test Interviews:** {len(interviews)}",
        f"- **Validated Riskiest Assumptions:** {len(validated_assumptions)} / {len(assumptions)}",
        f"- **Logged Weekly Sprints:** {len(sprints)}",
        "",
        "## Customer Paid-Pilot PACT Pipeline (Anonymized)",
        "| # | Segment / Archetype | Status | Value |",
        "| :--- | :--- | :--- | :--- |",
    ]
    if customer_pacts:
        for idx, p in enumerate(customer_pacts, 1):
            label = p.get("segment") or p.get("company") or f"Customer #{idx}"
            proof_lines.append(
                f"| {idx} | {label} | `{p.get('status', 'prospect')}` | {_fmt_money(p.get('amountUsd', 0))} |"
            )
    else:
        proof_lines.append("| — | No customer PACTs logged yet | `[HYPOTHESIS]` | $0 |")

    proof_lines.extend(["", "## Top Validated Assumptions"])
    if validated_assumptions:
        for a in validated_assumptions:
            proof_lines.append(f"- **[VALIDATED]** {a.get('statement', '')} *(Evidence: {a.get('evidence', 'Logged')})*")
    else:
        proof_lines.append("- No assumptions marked `[VALIDATED]` yet.")

    (d04 / "CUSTOMER_PROOF.md").write_text("\n".join(proof_lines) + "\n", encoding="utf-8")

    # 5. VC Lab / FI Diligence Readiness Checklist
    checks = [
        ("FI One-Sentence Pitch defined", bool(state.get("oneSentencePitch"))),
        ("Interactive Pitch Deck compiled (`02_Pitch_Deck/index.html`)", "index.html" in copied_deck),
        ("Live Founder Dashboard exported (`03_Metrics_and_PMF/index.html`)", "index.html" in copied_metrics),
        ("Customer Discovery logged (>= 3 Mom Test interviews)", len(interviews) >= 3),
        ("At least 1 Riskiest Assumption `[VALIDATED]`", len(validated_assumptions) >= 1),
        ("Customer Paid-Pilot PACT pipeline active", len(customer_pacts) >= 1),
        ("Sean Ellis PMF survey logged (`.startup/pmf.json`)", len(pmf_responses) >= 1),
        ("For-Progress iKPI defined", bool(ikpi.get("metric"))),
        ("Monthly Investor Update exported (`docs/INVESTOR_UPDATE.md`)", "INVESTOR_UPDATE.md" in copied_metrics),
    ]
    passed_count = sum(1 for _, ok in checks if ok)
    readiness_pct = round((passed_count / len(checks)) * 100)

    checklist_lines = [
        f"# {company} — VC Lab & Founder Institute Diligence Checklist",
        "",
        f"**Automated Data Room Readiness:** **{passed_count}/{len(checks)} ({readiness_pct}%)**",
        "",
        "## Automated Checks",
    ]
    for label, ok in checks:
        mark = "x" if ok else " "
        checklist_lines.append(f"- [{mark}] {label}")

    checklist_lines.extend([
        "",
        "## Legal & Corporate Hygiene (Verify with Startup Counsel)",
        "- [ ] Delaware C-Corp Certificate of Incorporation & Bylaws (e.g., Stripe Atlas / Clerky)",
        "- [ ] Signed Founder Stock Purchase Agreements & timely **83(b) Elections** filed with IRS",
        "- [ ] PIIA / IP Assignment signed by all founders, contractors, and advisors",
        "- [ ] Signed FI **FAST Agreements** for advisors & clean Cap Table (`docs/CAP_TABLE.md`)",
        "- [ ] Clean Financial Statements / QuickBooks Online P&L & Balance Sheet",
        "",
        "*Educational checklist only — not legal or tax advice.*",
    ])
    (d05 / "DILIGENCE_CHECKLIST.md").write_text("\n".join(checklist_lines) + "\n", encoding="utf-8")

    # Root DATA_ROOM_INDEX.md
    index_md = f"""# {company} — Investor Data Room Index

**Stage:** `{stage}` • **Readiness:** `{readiness_pct}% ({passed_count}/{len(checks)})` • **Updated:** {now_iso}

| Folder | Contents |
| :--- | :--- |
| `01_Executive_Summary/` | `ONE_PAGER.md` — FI pitch, validated metrics, iKPI & Mensarius Oath |
| `02_Pitch_Deck/` | {", ".join(f"`{f}`" for f in copied_deck) if copied_deck else "*(Compile `pitch-deck/index.html` to populate)*"} |
| `03_Metrics_and_PMF/` | {", ".join(f"`{f}`" for f in copied_metrics) if copied_metrics else "*(Run `founder_dashboard_build` / `pmf_engine_manage` to populate)*"} |
| `04_Pipeline_and_Proof/` | `CUSTOMER_PROOF.md` — PII-redacted PACT pipeline & validated assumptions |
| `05_Governance_and_Diligence/` | `DILIGENCE_CHECKLIST.md` — VC Lab / FI diligence & legal hygiene checklist |
"""
    (dr / "DATA_ROOM_INDEX.md").write_text(index_md, encoding="utf-8")

    # Sleek Zero-Dependency Local HTML Portal (data-room/index.html)
    esc_company = html.escape(str(company))
    esc_pitch = html.escape(str(pitch))
    deck_link = (
        '<a class="btn primary" href="02_Pitch_Deck/index.html">Open Interactive Pitch Deck</a>'
        if "index.html" in copied_deck
        else '<span class="muted">Pitch deck not compiled yet</span>'
    )
    dash_link = (
        '<a class="btn" href="03_Metrics_and_PMF/index.html">Open Live Metrics Dashboard</a>'
        if "index.html" in copied_metrics
        else '<span class="muted">Dashboard not compiled yet</span>'
    )
    check_items_html = "".join(
        f'<li class="{"ok" if ok else "todo"}">'
        f'<span>{"✓" if ok else "○"}</span> {html.escape(label)}</li>'
        for label, ok in checks
    )

    portal_html = f"""<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width,initial-scale=1" />
  <title>{esc_company} — Investor Data Room</title>
  <style>
    :root {{ --bg:#0b1120; --card:#111c33; --border:#1e293b; --text:#f8fafc; --muted:#94a3b8; --accent:#10b981; --amber:#f59e0b; }}
    * {{ box-sizing:border-box; }}
    body {{ margin:0; font-family:system-ui,-apple-system,Segoe UI,Roboto,sans-serif; background:var(--bg); color:var(--text); line-height:1.5; }}
    .wrap {{ max-width:980px; margin:0 auto; padding:32px 20px 64px; }}
    .badge {{ display:inline-block; padding:4px 10px; border-radius:999px; background:#064e3b; color:#6ee7b7; font-size:12px; font-weight:700; text-transform:uppercase; letter-spacing:.06em; }}
    h1 {{ margin:12px 0 6px; font-size:32px; }}
    .pitch {{ color:var(--muted); font-size:16px; margin:0 0 24px; }}
    .grid {{ display:grid; grid-template-columns:repeat(auto-fit,minmax(200px,1fr)); gap:14px; margin-bottom:24px; }}
    .card {{ background:var(--card); border:1px solid var(--border); border-radius:14px; padding:18px; }}
    .kpi-label {{ font-size:12px; color:var(--muted); text-transform:uppercase; letter-spacing:.05em; }}
    .kpi-val {{ font-size:26px; font-weight:800; margin-top:4px; }}
    .actions {{ display:flex; flex-wrap:wrap; gap:12px; margin-bottom:24px; }}
    .btn {{ display:inline-block; padding:10px 16px; border-radius:10px; text-decoration:none; font-weight:700; background:#1e293b; color:var(--text); border:1px solid #334155; }}
    .btn.primary {{ background:var(--accent); color:#022c22; border-color:var(--accent); }}
    ul.checks {{ list-style:none; padding:0; margin:12px 0 0; display:grid; gap:8px; }}
    ul.checks li {{ padding:8px 12px; border-radius:8px; background:#0f172a; border:1px solid var(--border); font-size:14px; }}
    ul.checks li.ok span {{ color:var(--accent); font-weight:800; margin-right:8px; }}
    ul.checks li.todo span {{ color:var(--amber); font-weight:800; margin-right:8px; }}
    .muted {{ color:var(--muted); font-size:13px; }}
    footer {{ margin-top:32px; color:var(--muted); font-size:12px; text-align:center; }}
  </style>
</head>
<body>
  <div class="wrap">
    <span class="badge">Investor Data Room • {html.escape(str(stage))}</span>
    <h1>{esc_company}</h1>
    <p class="pitch">{esc_pitch}</p>

    <div class="actions">
      {deck_link}
      {dash_link}
      <a class="btn" href="01_Executive_Summary/ONE_PAGER.md">Executive One-Pager</a>
      <a class="btn" href="04_Pipeline_and_Proof/CUSTOMER_PROOF.md">Customer Proof (PII-Redacted)</a>
      <a class="btn" href="05_Governance_and_Diligence/DILIGENCE_CHECKLIST.md">Diligence Checklist</a>
    </div>

    <div class="grid">
      <div class="card"><div class="kpi-label">Monthly Recurring Revenue</div><div class="kpi-val">{html.escape(_fmt_money(mrr))}</div></div>
      <div class="card"><div class="kpi-label">Gross Margin</div><div class="kpi-val">{html.escape(str(gm))}%</div></div>
      <div class="card"><div class="kpi-label">Sean Ellis PMF</div><div class="kpi-val">{html.escape(f"{sean_ellis_pct}%" if sean_ellis_pct is not None else "N/A")}</div></div>
      <div class="card"><div class="kpi-label">Data Room Readiness</div><div class="kpi-val">{readiness_pct}%</div></div>
    </div>

    <div class="card">
      <h2 style="margin:0 0 4px;font-size:18px;">VC Lab & Founder Institute Diligence Readiness ({passed_count}/{len(checks)})</h2>
      <div class="muted">Updated {html.escape(now_iso)} • All raw customer PII excluded by default.</div>
      <ul class="checks">{check_items_html}</ul>
    </div>

    <footer>Built with Startup Antigravity — Ethical Venture OS • Mensarius Oath Compliant</footer>
  </div>
</body>
</html>
"""
    (dr / "index.html").write_text(portal_html, encoding="utf-8")

    return {
        "ok": True,
        "dataRoomDir": str(dr),
        "portalHtml": str(dr / "index.html"),
        "indexMarkdown": str(dr / "DATA_ROOM_INDEX.md"),
        "readinessPct": readiness_pct,
        "checksPassed": passed_count,
        "checksTotal": len(checks),
        "copiedDeckFiles": copied_deck,
        "copiedMetricFiles": copied_metrics,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build an investor-ready Startup Antigravity Data Room.")
    parser.add_argument("--workspace", default=".", help="Path to startup workspace")
    args = parser.parse_args(argv)
    result = build_data_room(Path(args.workspace))
    print(json.dumps(result, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
