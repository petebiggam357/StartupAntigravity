    readiness_pct = round((passed_count / len(checks)) * 100)

    checklist_lines = [
        f"# {company} — VC Lab & Founder Institute Diligence Checklist",
        "",
        f"**Automated Data Room Readiness:** **{passed_count}/{len(checks)} ({readiness_pct}%)**",
        "",
        "## Automated Checks",
    ]
    for label, ok in checks:
        mark = "x" if ok else " "
        checklist_lines.append(f"- [{mark}] {label}")

