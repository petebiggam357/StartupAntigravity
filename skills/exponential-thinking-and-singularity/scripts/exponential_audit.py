#!/usr/bin/env python3
"""Deterministic Exponential Organizations (ExO), 6Ds of Exponentials & Accelerating Returns Engine.

Zero external dependencies (Python 3.10+ standard library only).
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

SIX_DS_ORDER = [
    ("digitized", "Digitized — Analog workflow becomes binary data, entering exponential growth."),
    ("deceptive", "Deceptive — Early doubling looks linear/tiny (0.01 -> 0.02 -> 0.04); incumbents ignore it."),
    ("disruptive", "Disruptive — Knee of the curve: quality/cost suddenly beats incumbents 10x."),
    ("demonetized", "Demonetized — Marginal cost collapses toward zero (e.g., AI inference & x402 rails)."),
    ("dematerialized", "Dematerialized — Physical hardware/offices/intermediaries vanish into software & agents."),
    ("democratized", "Democratized — Once-elite capabilities become accessible to billions globally."),
]

SCALE_KEYS = ("staff_on_demand", "community_crowd", "algorithms", "leveraged_assets", "engagement")
IDEAS_KEYS = ("interfaces", "dashboards", "experimentation", "autonomy", "social_tech")


def calc_exo_scorecard(args: dict[str, Any], workspace: Path | None = None) -> dict[str, Any]:
    """Score a startup's Massive Transformative Purpose (MTP) + SCALE + IDEAS attributes (0-100)."""
    company = str(args.get("company_name") or (workspace.name if workspace else "Startup")).strip()
    mtp = str(args.get("mtp") or "").strip()
    scale_in = args.get("scale") or {}
    ideas_in = args.get("ideas") or {}
    write_doc = bool(args.get("write_doc", False))

    scale_scores = {k: max(0, min(10, int(scale_in.get(k, 5)))) for k in SCALE_KEYS}
    ideas_scores = {k: max(0, min(10, int(ideas_in.get(k, 5)))) for k in IDEAS_KEYS}

    mtp_points = 10 if len(mtp.split()) >= 5 else (4 if mtp else 0)
    scale_sum = sum(scale_scores.values())  # /50
    ideas_sum = sum(ideas_scores.values())  # /50
    exo_quotient = round(((mtp_points + scale_sum + ideas_sum) / 110.0) * 100.0, 1)

    all_attrs = [*(("SCALE", k, v) for k, v in scale_scores.items()), *(("IDEAS", k, v) for k, v in ideas_scores.items())]
    weakest = sorted(all_attrs, key=lambda x: x[2])[:3]
    recommendations = [
        f"Upgrade {grp}.{k.replace('_', ' ')} (currently {v}/10) to unlock 10x output without linear headcount."
        for grp, k, v in weakest
    ]
    if not mtp:
        recommendations.insert(0, "Define a crisp Massive Transformative Purpose (MTP) tied to a Global Grand Challenge & UN SDG iKPI.")

    tier = (
        "EXPONENTIAL_READY" if exo_quotient >= 75.0
        else ("HYBRID_TRANSITIONING" if exo_quotient >= 50.0 else "LINEAR_ORGANIZATION")
    )

    doc_path: str | None = None
    if write_doc and workspace is not None:
        docs_dir = workspace / "docs"
        docs_dir.mkdir(parents=True, exist_ok=True)
        bp = docs_dir / "EXPONENTIAL_BLUEPRINT.md"
        now_iso = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
        lines = [
            f"# {company} — Exponential Organization (ExO) Blueprint",
            "",
            f"> Generated by Startup Antigravity (`exponential_audit`) • {now_iso}",
            f"> **ExO Quotient:** **{exo_quotient} / 100** (`{tier}`)",
            "",
            "## Massive Transformative Purpose (MTP)",
            f"> {mtp or '[HYPOTHESIS] Define a bold, 10x Massive Transformative Purpose.'}",
            "",
            "## SCALE (External Abundance Engines)",
            *[f"- **{k.replace('_', ' ').title()}:** `{v}/10`" for k, v in scale_scores.items()],
            "",
            "## IDEAS (Internal Control & Velocity Interfaces)",
            *[f"- **{k.replace('_', ' ').title()}:** `{v}/10`" for k, v in ideas_scores.items()],
            "",
            "## Top 3 Exponential Leverage Upgrades",
            *[f"{i}. {r}" for i, r in enumerate(recommendations[:3], 1)],
            "",
            "*Educational adaptation inspired by Singularity & ExO frameworks — paired with FI revenue-first discipline and Mensarius Oath ethics.*",
        ]
        bp.write_text("\n".join(lines) + "\n", encoding="utf-8")
        doc_path = str(bp)

    return {
        "action": "exo_scorecard",
        "company": company,
        "mtp": mtp or None,
        "exoQuotient": exo_quotient,
        "tier": tier,
        "scaleScores": scale_scores,
        "ideasScores": ideas_scores,
        "topLeverageUpgrades": recommendations[:3],
        "blueprintPath": doc_path,
    }


def calc_six_ds_map(args: dict[str, Any]) -> dict[str, Any]:
    """Map a startup's industry onto the 6Ds of Exponentials and generate Why-Now strategy notes."""
    industry = str(args.get("industry") or "Target Industry").strip()
    current_d = str(args.get("current_stage", "deceptive")).strip().lower()
    valid_keys = [k for k, _ in SIX_DS_ORDER]
    if current_d not in valid_keys:
        raise ValueError(f"current_stage must be one of: {', '.join(valid_keys)}")

    idx = valid_keys.index(current_d)
    next_d = valid_keys[idx + 1] if idx + 1 < len(valid_keys) else "democratized"
    playbook = {
        "digitized": "Capture proprietary structured data now before incumbents notice the digital shift.",
        "deceptive": "Prime window to build quietly with early adopters & Paid-Pilot PACTs before the knee of the curve hits.",
        "disruptive": "Lead your pitch with 'Why Now': show 10x faster/cheaper proof beating legacy incumbents today.",
        "demonetized": "Do not sell raw commodity compute/data—monetize workflow outcomes, trust, and x402 agent distribution.",
        "dematerialized": "Replace legacy physical overhead with zero-ops software, APIs, and autonomous workflows.",
        "democratized": "Win via community, global distribution (e.g., USDC/x402 rails), and brand trust.",
    }[current_d]

    return {
        "action": "six_ds_map",
        "industry": industry,
        "currentD": current_d,
        "stageIndex": idx + 1,
        "nextInflectionD": next_d,
        "whyNowStrategy": playbook,
        "sixDsReference": [{"stage": k, "meaning": desc} for k, desc in SIX_DS_ORDER],
    }


def calc_accelerating_returns_sim(args: dict[str, Any]) -> dict[str, Any]:
    """Model how annual AI/compute price-performance gains expand gross margin over 12, 24, and 36 months."""
    arpu = float(args.get("monthly_arpu_usd", 100.0))
    current_ai_cogs = float(args.get("current_monthly_ai_cogs_usd", 35.0))
    other_cogs = float(args.get("other_monthly_cogs_usd", 5.0))
    annual_perf_multiplier = max(1.1, float(args.get("annual_price_perf_multiplier", 2.5)))

    projections: list[dict[str, Any]] = []
    for year in (0, 1, 2, 3):
        ai_cost = current_ai_cogs / (annual_perf_multiplier ** year)
        total_cogs = ai_cost + other_cogs
        margin_pct = ((arpu - total_cogs) / arpu * 100.0) if arpu > 0 else 0.0
        projections.append(
            {
                "year": year,
                "label": "Today" if year == 0 else f"Month {year * 12}",
                "aiCogsUsd": round(ai_cost, 2),
                "totalCogsUsd": round(total_cogs, 2),
                "grossMarginPct": round(margin_pct, 2),
                "meets75PctFloor": margin_pct >= 75.0,
            }
        )

    return {
        "action": "accelerating_returns_sim",
        "monthlyArpuUsd": arpu,
        "annualPricePerfMultiplier": annual_perf_multiplier,
        "projections": projections,
        "founderTakeaway": (
            "Design for where AI price-performance will be in 18–24 months (Law of Accelerating Returns), "
            "while using model routing & caching today so you never bleed cash while waiting."
        ),
    }


def run_exponential_audit(args: dict[str, Any], workspace: Path | None = None) -> dict[str, Any]:
    action = str(args.get("action", "exo_scorecard")).strip()
    if action == "exo_scorecard":
        return calc_exo_scorecard(args, workspace=workspace)
    if action == "six_ds_map":
        return calc_six_ds_map(args)
    if action == "accelerating_returns_sim":
        return calc_accelerating_returns_sim(args)
    raise ValueError(
        f"Unknown exponential_audit action '{action}'. Use 'exo_scorecard', 'six_ds_map', or 'accelerating_returns_sim'."
    )


if __name__ == "__main__":
    import sys

    payload = json.loads(sys.argv[1]) if len(sys.argv) > 1 else {"action": "exo_scorecard"}
    print(json.dumps(run_exponential_audit(payload, Path.cwd()), indent=2))
